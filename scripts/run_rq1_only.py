#!/usr/bin/env python3
"""Run only the controlled RQ1 ablation after runtime admission.

No changes to the package's machine.local.json or previous runs. Runtime
qualification must cover all ten declared libraries with complete original,
plain-Graal and profiled suite signatures and valid trace mapping.
"""
import argparse,json,sys,traceback
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from experiments.common import Context,read,write,sha,same
from experiments import prepare
from experiments.rq1 import run as rq1

def require(condition,message):
 if not condition:raise ValueError(message)

def admit(path,plan):
 proof=read(path)
 require(isinstance(proof,dict),'Runtime admission must be a JSON object generated by qualify_rq1_runtime.py; a diagnostic row list is not admission')
 require(proof.get('schemaVersion')==1,'Unsupported admission schema')
 require(proof.get('status')=='qualified','Runtime admission is not complete and qualified')
 require(set(proof.get('libraries',{}))==set(plan['libraries']),'Admission must cover all ten libraries')
 require(set(proof.get('runtimeByLibrary',{}))<=set(plan['libraries']),'Runtime override names an undeclared library')
 for lib,row in proof['libraries'].items():
  runtime=proof.get('runtimeByLibrary',{}).get(lib,proof['runtime'])
  require(row.get('fullSuite') is True,lib+': test discovery is not a full suite')
  require(row.get('productionUnchanged') is True,lib+': source changed')
  require(row.get('mappingValid') is True and row.get('traceBalanced') is True,lib+': invalid trace/mapping')
  require(same(row.get('original'),row.get('plainGraal')),lib+': plain runtime suite differs')
  require(same(row.get('original'),row.get('profiled')),lib+': profiled runtime suite differs')
  require(row['plainGraal']['command'][0]==runtime['graalNode']['path'],lib+': plain test used a different runtime')
  require(row['profiled']['command'][0]==runtime['graalNode']['path'] and '--nodeprof' in row['profiled']['command'],lib+': no matching NodeProf command')
  for field in ['original','plainGraal','profiled']:
   stage=row[field];log=Path(stage['log']);require(log.is_file() and sha(log)==stage['logSha256'],lib+': unverifiable suite log')
 for name in ['graalNode','nodeprofLoader','nodeprofJar']:
  x=proof['runtime'][name];require(Path(x['path']).is_file() and sha(x['path'])==x['sha256'],'Runtime identity mismatch: '+name)
 for lib,runtime in proof.get('runtimeByLibrary',{}).items():
  for name in ['graalNode','nodeprofLoader','nodeprofJar']:
   x=runtime[name];require(Path(x['path']).is_file() and sha(x['path'])==x['sha256'],'Runtime override identity mismatch: '+lib+'/'+name)
 for lib,deps in proof.get('runtimeDependenciesByLibrary',{}).items():
  x=deps['underlyingNode'];require(Path(x['path']).is_file() and sha(x['path'])==x['sha256'],'Underlying library runtime changed: '+lib)
 if proof.get('runtimeDependencies'):
  x=proof['runtimeDependencies']['underlyingNode'];require(Path(x['path']).is_file() and sha(x['path'])==x['sha256'],'Underlying wrapped runtime changed')
 require(bool(proof.get('analysisSources')),'Admission must include analysis source hashes')
 for filename,expected in proof['analysisSources'].items():
  require(Path(filename).is_file() and sha(filename)==expected,'Analysis source changed after runtime admission: '+filename)
 return proof

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--run-id',required=True);p.add_argument('--runtime-qualification',required=True);a=p.parse_args()
 plan=read(Path(__file__).resolve().parents[1]/'experiments/rq1/ablation-plan-20261102.json')
 try:proof=admit(a.runtime_qualification,plan)
 except (ValueError,KeyError,TypeError,OSError) as exc:p.error(str(exc))
 if proof.get('runtimeByLibrary'):p.error('Library-specific runtimes require scripts/run_ordered_revision.py, which selects and records each qualified runtime explicitly')
 c=Context(a.run_id)
 try:
  for name in ['graalNode','nodeprofLoader','nodeprofJar']:c.machine[name]=proof['runtime'][name]['path']
  c.protocol['arms']=plan['arms'];c.protocol['researchQuestions']=['rq1']
  write(c.out/'effective-machine.json',c.machine);write(c.out/'effective-protocol.json',c.protocol)
  write(c.out/'ablation-plan.json',plan);write(c.out/'runtime-qualification.json',proof)
  c.record['scope']='RQ1 only; no recovery-loading or runtime/cost measurements'
  prepare.run(c)
  require(set(c.qualified)==set(plan['libraries']),'All ten target inputs must qualify before RQ1')
  for lib,q in c.qualified.items():
   require(q['root'].resolve()==Path(proof['libraries'][lib]['sourceRoot']).resolve(),'Admission root mismatch: '+lib)
   files=read(q['scope'])['files'];expected=proof['libraries'][lib]['sourceHashes']
   require(set(files)==set(expected),'Admission scope mismatch: '+lib)
   require(all(sha(q['root']/f)==expected[f] for f in files),'Admission source mismatch: '+lib)
  rq1.run(c,qualification=False)
  c.finish()
 except Exception:
  c.record.update(status='failed',error=traceback.format_exc());c.save();raise
 print(c.out/'status.json')
if __name__=='__main__':main()
